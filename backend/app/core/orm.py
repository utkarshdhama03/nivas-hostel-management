"""Shared column helpers for ORM models, so every model spells types the same way.

The database (backend/migrations/sql/) is the source of truth; these helpers only
describe it to SQLAlchemy. tests/test_model_drift.py fails if a model disagrees
with the real table (missing/extra column, wrong nullability).
"""

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import DateTime, Integer, Uuid, text
from sqlalchemy.orm import Mapped, mapped_column

UUID_PK_DEFAULT = text("uuidv7()")
NOW = text("now()")  # real time: security tables (D67)
APP_NOW = text("app_now()")  # business time: follows app.now, set per transaction (app/core/db.py)


def uuid_pk() -> Mapped[uuid.UUID]:
    """Primary key generated by PostgreSQL (uuidv7(), time-ordered); returned via RETURNING."""
    return mapped_column(Uuid, primary_key=True, server_default=UUID_PK_DEFAULT)


def created_at(clock: str = "business") -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=APP_NOW if clock == "business" else NOW)


def updated_at(clock: str = "business") -> Mapped[datetime]:
    """clock="real" for security tables (users, platform accounts): their timestamps can't be backdated."""
    when = APP_NOW if clock == "business" else NOW
    return mapped_column(DateTime(timezone=True), server_default=when, onupdate=when)


def version_column() -> Mapped[int]:
    """Optimistic locking (Q70). Used with __mapper_args__ = {"version_id_col": version}:
    SQLAlchemy adds "AND version = <old>" to every UPDATE and increments it; zero rows
    updated raises StaleDataError, which the API turns into 409 edit_conflict."""
    return mapped_column(Integer, server_default=text("1"), nullable=False)


def tz(nullable: bool = True, **kw: Any) -> Mapped[Any]:
    return mapped_column(DateTime(timezone=True), nullable=nullable, **kw)
