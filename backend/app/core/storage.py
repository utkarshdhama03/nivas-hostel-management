"""File storage (docs/02 §9): the database holds metadata, this holds bytes.

    StorageBackend   save(key, data) · open(key) · delete(key) · exists(key)
      LocalFileStorage   a directory (the `uploads` Docker volume), now
      (S3-compatible, e.g. self-hosted MinIO, later and only if needed)

Keys are generated by the server ("<org>/<category>/<yyyy>/<mm>/<uuid>") and the database
CHECKs their format, so a file name from a user can never become a path. Writes go to a
temporary file first and are moved into place atomically: a crash never leaves half a file
under a real key.
"""

from __future__ import annotations

import os
import re
import tempfile
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from app.core.config import get_settings

KEY_RE = re.compile(r"^[0-9a-f-]{36}/[a-z_]+/[0-9]{4}/[0-9]{2}/[0-9a-f-]{36}$")  # same as the DB CHECK


class StorageError(Exception):
    pass


class StorageBackend(Protocol):
    def save(self, key: str, data: bytes) -> None: ...
    def open(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...
    def exists(self, key: str) -> bool: ...


class LocalFileStorage:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root)

    def _path(self, key: str) -> Path:
        if not KEY_RE.match(key):
            raise StorageError("invalid storage key")
        return self.root / key

    def save(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
                fh.flush()
                os.fsync(fh.fileno())
            os.replace(tmp, path)  # atomic on the same filesystem
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

    def open(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as exc:
            raise StorageError("file missing from storage") from exc

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        return self._path(key).exists()


@lru_cache(maxsize=1)
def get_storage() -> StorageBackend:
    return LocalFileStorage(get_settings().hms_upload_dir)
